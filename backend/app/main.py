"""The API, and the built front end when it exists."""

import importlib
import pkgutil
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import FastAPI
from fastapi.staticfiles import StaticFiles

from app import routes
from app.database import connect, init_db


@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    """Create the database file and its tables when the product starts."""
    connection = connect()
    init_db(connection)
    connection.close()
    yield


app = FastAPI(title="Sentence cards generator", lifespan=lifespan)

# A new endpoint is a new module in `app/routes` with a `router`, so tasks do not edit this file.
for module in pkgutil.iter_modules(routes.__path__):
    app.include_router(importlib.import_module(f"{routes.__name__}.{module.name}").router)


@app.get("/api/health")
def health() -> dict[str, str]:
    return {"status": "ok"}


# Serve the built front end from the same address as the API, so one command runs the product.
FRONTEND_BUILD = Path(__file__).resolve().parents[2] / "frontend" / "dist"
if FRONTEND_BUILD.is_dir():
    app.mount("/", StaticFiles(directory=FRONTEND_BUILD, html=True), name="frontend")
